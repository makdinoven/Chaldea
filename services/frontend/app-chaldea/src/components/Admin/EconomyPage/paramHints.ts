/**
 * FEAT-185 — texts of the «?» hints on every economy parameter, in one place so they are easy to edit.
 *
 * Facts come from character-service: `econ_sim.py` (SimParams defaults, the tick maths), `econ_merchant.py`,
 * `econ_bank.py` and `schemas.ECON_SIM_PARAM_BOUNDS`. For the simulation params the default and the allowed range
 * are NOT repeated here — `ParamHint` takes them from the param definitions of `EconomyTick.tsx` (which mirror the
 * backend), so they cannot drift apart. Other fields carry them as text in `def` / `range`.
 *
 * One «шаг» = one recalculation = 6 hours, 4 steps a day. A share «за шаг» s gives 1 − (1 − s)^4 a day.
 */
import type { EconSimParams } from '../../../types/economy';

export interface ParamHintText {
  /** What the parameter does — plain words. */
  what: string;
  /** What happens if it is raised. */
  up?: string;
  /** What happens if it is lowered. */
  down?: string;
  /** Safe range in words / numbers. */
  safe?: string;
  /** Default as text — only for fields whose default is not a sim param. */
  def?: string;
  /** Allowed range as text — only for fields whose bounds are not a sim param. */
  range?: string;
}

